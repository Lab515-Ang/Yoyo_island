def unlock_text(u):
    k = u['kind']
    if k == 'start':
        return '一開始就能找'
    if k == 'project':
        return f"修好「{PROJECT_TITLE.get(u['id'], u['id'])}」"
    if k == 'coins':
        return f"商店 {u['price']:,} 金幣"
    if k == 'gems':
        return f"商店 {u['price']} 寶石"
    if k == 'iap':
        return 'Plus 會員'
    return k


